"""
SentinelOT — Compliance Report Generator
Pulls real asset inventory and alert history from the database and
renders a structured HTML report, framed around CERT-In's cybersecurity
incident-reporting categories and DPDPA's breach-notification relevance.
This supports a plant's compliance documentation -- it is not itself a
certified compliance product, and is labeled as such in the report.
"""
import os
import psycopg2
import psycopg2.extras
from datetime import datetime, timezone
from jinja2 import Template

DATABASE_URL = os.environ["DATABASE_URL"]
SITE_ID = os.environ.get("SITE_ID", "22222222-2222-2222-2222-222222222222")
REPORT_DAYS = int(os.environ.get("REPORT_DAYS", "30"))

TEMPLATE = """
<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>SentinelOT Compliance Report</title>
<style>
body { font-family: Arial, sans-serif; max-width: 900px; margin: 40px auto; color: #1a1a1a; }
h1 { border-bottom: 3px solid #2563eb; padding-bottom: 10px; }
h2 { color: #2563eb; margin-top: 32px; }
table { width: 100%; border-collapse: collapse; margin: 12px 0; }
th, td { border: 1px solid #ccc; padding: 8px; text-align: left; font-size: 14px; }
th { background: #f0f4ff; }
.severity-critical { color: #b91c1c; font-weight: bold; }
.severity-high { color: #c2410c; font-weight: bold; }
.severity-medium { color: #a16207; }
.disclaimer { background: #fef3c7; padding: 12px; border-radius: 6px; font-size: 13px; margin-top: 24px; }
</style></head><body>

<h1>SentinelOT OT Security Monitoring Report</h1>
<p><strong>Site:</strong> {{ site_name }} &nbsp; | &nbsp;
<strong>Period:</strong> {{ period_start }} to {{ period_end }} &nbsp; | &nbsp;
<strong>Generated:</strong> {{ generated_at }}</p>

<h2>1. Monitored Asset Inventory</h2>
<p>{{ assets|length }} device(s) passively discovered on the OT network during this period.</p>
<table>
<tr><th>IP Address</th><th>Role</th><th>Protocols</th><th>Criticality</th><th>First Seen</th><th>Last Seen</th></tr>
{% for a in assets %}
<tr><td>{{ a.ip_address }}</td><td>{{ a.device_role }}</td><td>{{ a.protocols|join(', ') if a.protocols else 'n/a' }}</td>
<td>{{ a.criticality }}</td><td>{{ a.first_seen.strftime('%Y-%m-%d %H:%M') }}</td><td>{{ a.last_seen.strftime('%Y-%m-%d %H:%M') }}</td></tr>
{% endfor %}
</table>

<h2>2. Security Alerts Summary</h2>
<p>{{ alerts|length }} alert(s) recorded during this period.</p>
<table>
<tr><th>Time</th><th>Severity</th><th>Description</th><th>Plain-Language Explanation</th><th>Status</th></tr>
{% for al in alerts %}
<tr><td>{{ al.time.strftime('%Y-%m-%d %H:%M') }}</td><td class="severity-{{ al.severity }}">{{ al.severity|upper }}</td>
<td>{{ al.description }}</td><td>{{ al.llm_explanation or 'pending' }}</td><td>{{ al.status }}</td></tr>
{% endfor %}
</table>

<h2>3. Severity Breakdown</h2>
<table>
<tr><th>Severity</th><th>Count</th></tr>
{% for sev, count in severity_counts.items() %}
<tr><td>{{ sev|upper }}</td><td>{{ count }}</td></tr>
{% endfor %}
</table>

<h2>4. Monitoring Coverage</h2>
<p>Passive, non-intrusive network monitoring active throughout the reporting period, covering: {{ protocols_covered|join(', ') }}.
No active scanning or intrusive probing was performed on any monitored device.</p>

<div class="disclaimer">
<strong>Scope note:</strong> This report documents OT network monitoring activity and security events
for internal review and audit-support purposes, referencing categories aligned with CERT-In's
cybersecurity incident reporting guidelines and DPDPA's breach-notification relevance where applicable.
It is generated by an automated monitoring system and is intended to support -- not replace --
a plant's formal compliance and audit processes.
</div>

</body></html>
"""


def main():
    conn = psycopg2.connect(DATABASE_URL)
    cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)

    cur.execute("SELECT name FROM sites WHERE id = %s", (SITE_ID,))
    site = cur.fetchone()
    site_name = site["name"] if site else "Unknown Site"

    cur.execute(
        """SELECT ip_address, device_role, protocols, criticality, first_seen, last_seen
           FROM assets WHERE site_id = %s ORDER BY first_seen""",
        (SITE_ID,),
    )
    assets = cur.fetchall()

    cur.execute(
        """SELECT time, severity, description, llm_explanation, status
           FROM alerts WHERE site_id = %s AND time >= now() - interval '%s days'
           ORDER BY time DESC""",
        (SITE_ID, REPORT_DAYS),
    )
    alerts = cur.fetchall()

    severity_counts = {}
    for al in alerts:
        severity_counts[al["severity"]] = severity_counts.get(al["severity"], 0) + 1

    protocols_covered = sorted({p for a in assets for p in (a["protocols"] or [])}) or ["modbus_tcp", "s7comm"]

    html = Template(TEMPLATE).render(
        site_name=site_name,
        period_start=(datetime.now(timezone.utc)).strftime("%Y-%m-%d"),
        period_end=datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        generated_at=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        assets=assets,
        alerts=alerts,
        severity_counts=severity_counts,
        protocols_covered=protocols_covered,
    )

    with open("/reports/compliance_report.html", "w") as f:
        f.write(html)
    print(f"Report generated: {len(assets)} assets, {len(alerts)} alerts -> /reports/compliance_report.html")


if __name__ == "__main__":
    main()
